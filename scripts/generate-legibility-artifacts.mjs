import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { collectEntrypointSymbols } from './typescript-export-inventory.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');
const docsGeneratedDir = path.join(rootDir, 'docs', 'generated');

const packageJson = JSON.parse(
  fs.readFileSync(path.join(rootDir, 'package.json'), 'utf8')
);

const exportSourceByKey = {
  '.': path.join(rootDir, 'src', 'index.ts'),
  './greebles': path.join(rootDir, 'src', 'greebles', 'index.ts'),
  './capitalships': path.join(rootDir, 'src', 'capitalships', 'index.ts'),
};

const playgroundMetadata = {
  'index.html': {
    focus: 'Combined playground for capital ship generation and its greeble library.',
    knobs:
      'Uses tabbed controls plus seed, hue, archetype, and mode selectors for quick visual debugging.',
  },
  'greeble_showcase.html': {
    focus: 'Gallery of low-level greeble primitives and surface treatments.',
    knobs:
      'Best for seed-based visual diffs of panel, window, pipe, hose, and trench variants.',
  },
  'element_showcase.html': {
    focus: 'Capital ship component renderer showcase.',
    knobs:
      'Good for isolating hull, engine, weapon, storage, and tower rendering changes.',
  },
};

function readText(filePath) {
  return fs.readFileSync(filePath, 'utf8');
}

function titleForExportKey(exportKey) {
  if (exportKey === '.') {
    return '`ship-shape`';
  }
  return `\`ship-shape/${exportKey.replace('./', '')}\``;
}

function generatePublicApiInventory() {
  const lines = [
    '# Public API Inventory',
    '',
    'Generated by `npm run generate:legibility` from the supported package entrypoints.',
    'Deep `src/...` imports are internal-only and are intentionally excluded.',
    '',
  ];

  for (const exportKey of ['.', './greebles', './capitalships']) {
    const exportConfig = packageJson.exports[exportKey];
    const symbols = collectEntrypointSymbols(exportSourceByKey[exportKey]);
    lines.push(`## ${titleForExportKey(exportKey)}`);
    lines.push('');
    lines.push(`- Import target: \`${exportKey === '.' ? 'ship-shape' : `ship-shape/${exportKey.replace('./', '')}`}\``);
    lines.push(`- Runtime path: \`${exportConfig.import}\``);
    lines.push(`- Types path: \`${exportConfig.types}\``);
    lines.push('- Supported symbols:');
    for (const symbol of symbols) {
      lines.push(`  - \`${symbol}\``);
    }
    lines.push('');
  }

  return `${lines.join('\n').trim()}\n`;
}

function generatePlaygroundInventory() {
  const htmlFiles = fs
    .readdirSync(path.join(rootDir, 'www'))
    .filter((file) => file.endsWith('.html'))
    .sort((a, b) => a.localeCompare(b));

  const lines = [
    '# Playground Inventory',
    '',
    'Generated by `npm run generate:legibility` from the `www/` runtime entrypoints.',
    '',
  ];

  for (const htmlFile of htmlFiles) {
    const htmlSource = readText(path.join(rootDir, 'www', htmlFile));
    const scriptEntries = [...htmlSource.matchAll(/<script\b[^>]*type=["']module["'][^>]*src=["']([^"']+)["'][^>]*>/g)]
      .map((match) => match[1])
      .map((src) => src.replace(/^\//, ''))
      .filter((src) => src.endsWith('.ts'))
      .sort((a, b) => a.localeCompare(b));
    const metadata = playgroundMetadata[htmlFile] ?? {
      focus: 'General-purpose runtime surface in `www/`.',
      knobs: 'Inspect the companion script for the available controls and seed inputs.',
    };
    lines.push(`## \`${htmlFile}\``);
    lines.push('');
    lines.push(`- HTML entry: [\`${htmlFile}\`](../../www/${htmlFile})`);
    if (scriptEntries.length === 0) {
      lines.push('- Script entries: none');
    } else {
      lines.push('- Script entries:');
      for (const scriptEntry of scriptEntries) {
        lines.push(`  - [\`${scriptEntry}\`](../../www/${scriptEntry})`);
      }
    }
    lines.push(`- Focus: ${metadata.focus}`);
    lines.push(`- Debugging knobs: ${metadata.knobs}`);
    lines.push('');
  }

  return `${lines.join('\n').trim()}\n`;
}

function writeFileOrCheck(relativePath, content, checkOnly) {
  const filePath = path.join(rootDir, relativePath);
  if (!checkOnly) {
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, content, 'utf8');
    return;
  }

  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (current !== content) {
    throw new Error(
      `${relativePath} is out of date. Run \`npm run generate:legibility\` and commit the result.`
    );
  }
}

function main() {
  const checkOnly = process.argv.includes('--check');
  fs.mkdirSync(docsGeneratedDir, { recursive: true });

  const outputs = new Map([
    ['docs/generated/public-api-inventory.md', generatePublicApiInventory()],
    ['docs/generated/playground-inventory.md', generatePlaygroundInventory()],
  ]);

  for (const [relativePath, content] of outputs) {
    writeFileOrCheck(relativePath, content, checkOnly);
  }

  if (!checkOnly) {
    console.log('Updated legibility artifacts in docs/generated/.');
  }
}

try {
  main();
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
